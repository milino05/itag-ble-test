import assert from 'node:assert/strict';
import {ReadPerformance} from './perf.mjs';
const m = new ReadPerformance(10000);
m.start(1000);
for(let i=1;i<=10;i++)m.add(1000+i*200,100);
let s=m.snapshot(3000);
assert.equal(s.total,10);
assert.ok(Math.abs(s.readsPerSecond-5)<0.01);
assert.equal(s.meanLatency,100);
assert.equal(s.warmedUp,false);
for(let i=1;i<=10;i++)m.add(3000+i*600,350);
s=m.snapshot(9000);
assert.ok(s.readsPerSecond < 4);
assert.ok(s.meanLatency > 100);
assert.equal(s.warmedUp,true);
const m2 = new ReadPerformance(1000);
m2.start(0);
m2.add(99,50);
m2.add(1100,250);
assert.equal(m2.snapshot(1100).samples,1);
m2.add(1200,120,false);
assert.equal(m2.snapshot(1200).failures,1);
m2.reset();
assert.equal(m2.snapshot(3000).total,0);
console.log('Performance rolling-window tests: OK');
